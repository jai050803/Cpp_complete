// Program 1: Basic Data Types
#include <iostream>
using namespace std;
int main() {
    int a = 10;
    float b = 5.5;
    char c = 'A';
    double d = 12.345;
    bool e = true;
    cout << "int: " << a << "\n";
    cout << "float: " << b << "\n";
    cout << "char: " << c << "\n";
    cout << "double: " << d << "\n";
    cout << "bool: " << e << "\n";
    return 0;
}